#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
==============================================================================
 DASHBOARD HTML GZIP GENERATOR & SYNCHRONIZER FOR ESP32-CAM FIRMWARE
==============================================================================
 Usage:
   python scripts/compress_dashboard.py              # Regenerate include/dashboard_html_gz.h from src/main.cpp
   python scripts/compress_dashboard.py --check      # Check if header is up to date with src/main.cpp
   python scripts/compress_dashboard.py --sync-html  # Export DASHBOARD_HTML in src/main.cpp -> Rice_Dashboard.html
   python scripts/compress_dashboard.py --from-html  # Import Rice_Dashboard.html -> src/main.cpp + dashboard_html_gz.h
   python scripts/compress_dashboard.py --help       # Show help options
==============================================================================
"""

import sys
import os
import re
import gzip
import argparse

def get_default_paths():
    base_dir = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    main_cpp = os.path.join(base_dir, "src", "main.cpp")
    gz_header = os.path.join(base_dir, "include", "dashboard_html_gz.h")
    return base_dir, main_cpp, gz_header

def extract_html_from_main(main_cpp_path):
    if not os.path.isfile(main_cpp_path):
        raise FileNotFoundError(f"Cannot find source file: {main_cpp_path}")
    with open(main_cpp_path, "r", encoding="utf-8") as f:
        content = f.read()

    pattern = r'static\s+const\s+char\s+DASHBOARD_HTML\[\]\s+PROGMEM\s*=\s*R"rawliteral\((.*?)\)rawliteral";'
    match = re.search(pattern, content, re.DOTALL)
    if not match:
        raise ValueError(f"Could not find DASHBOARD_HTML raw literal in {main_cpp_path}")
    
    # Strip leading/trailing newlines to keep clean HTML
    html = match.group(1).lstrip("\r\n").rstrip("\r\n")
    return html

def embed_html_into_main(main_cpp_path, html_text):
    if not os.path.isfile(main_cpp_path):
        raise FileNotFoundError(f"Cannot find source file: {main_cpp_path}")
    with open(main_cpp_path, "r", encoding="utf-8") as f:
        content = f.read()

    pattern = r'(static\s+const\s+char\s+DASHBOARD_HTML\[\]\s+PROGMEM\s*=\s*R"rawliteral\()(\r?\n?.*?)(\)rawliteral";)'
    if not re.search(pattern, content, re.DOTALL):
        raise ValueError(f"Could not find DASHBOARD_HTML pattern to replace in {main_cpp_path}")

    clean_html = "\n" + html_text.strip("\r\n") + "\n"
    new_content = re.sub(pattern, lambda m: m.group(1) + clean_html + m.group(3), content, flags=re.DOTALL)
    with open(main_cpp_path, "w", encoding="utf-8", newline="\n") as f:
        f.write(new_content)

def extract_html_from_file(file_path):
    with open(file_path, "r", encoding="utf-8") as f:
        return f.read().lstrip("\r\n").rstrip("\r\n")

def read_current_gz_header(header_path):
    if not os.path.isfile(header_path):
        return None, None
    with open(header_path, "r", encoding="utf-8") as f:
        content = f.read()

    m_len = re.search(r'DASHBOARD_HTML_GZ_LEN\s*=\s*(\d+);', content)
    declared_len = int(m_len.group(1)) if m_len else None

    hex_bytes = re.findall(r'0x([0-9a-fA-F]{2})', content)
    raw_bytes = bytes(int(b, 16) for b in hex_bytes)
    return declared_len, raw_bytes

def compress_html(html_text):
    data = html_text.encode("utf-8")
    # mtime=0 guarantees deterministic compressed output across different machines/runs
    compressed = gzip.compress(data, compresslevel=9, mtime=0)
    return data, compressed

def generate_header_content(compressed_bytes, raw_size):
    hex_lines = []
    chunk_size = 16
    for i in range(0, len(compressed_bytes), chunk_size):
        chunk = compressed_bytes[i:i + chunk_size]
        hex_str = ", ".join(f"0x{b:02x}" for b in chunk)
        hex_lines.append(f"    {hex_str}")

    joined_bytes = ",\n".join(hex_lines)

    header = f"""// ==============================================================================
// Auto-generated pre-compressed GZIP dashboard HTML
// Generated by scripts/compress_dashboard.py
// Raw size: {raw_size:,} bytes | GZIP size: {len(compressed_bytes):,} bytes ({len(compressed_bytes) * 100.0 / raw_size:.1f}%)
// Run: python scripts/compress_dashboard.py to regenerate when DASHBOARD_HTML changes.
// ==============================================================================
#ifndef DASHBOARD_HTML_GZ_H
#define DASHBOARD_HTML_GZ_H

#include <Arduino.h>

#define HAVE_DASHBOARD_HTML_GZ 1

static const size_t DASHBOARD_HTML_GZ_LEN = {len(compressed_bytes)};
static const uint8_t DASHBOARD_HTML_GZ[] PROGMEM = {{
{joined_bytes}
}};

#endif // DASHBOARD_HTML_GZ_H
"""
    return header

def check_sync(main_cpp_path, gz_header_path, verbose=True):
    if verbose:
        print(f"[*] Checking sync between:\n    Source: {main_cpp_path}\n    Header: {gz_header_path}")
    raw_html = extract_html_from_main(main_cpp_path)
    dec_len, gz_bytes = read_current_gz_header(gz_header_path)
    if gz_bytes is None:
        if verbose:
            print("[!] GZIP header file does not exist.")
        return False

    if dec_len != len(gz_bytes):
        if verbose:
            print(f"[!] Length mismatch: declared={dec_len}, actual={len(gz_bytes)}")
        return False

    try:
        decompressed = gzip.decompress(gz_bytes).decode("utf-8")
    except Exception as e:
        if verbose:
            print(f"[!] Decompression error: {e}")
        return False

    if decompressed == raw_html:
        if verbose:
            print(f"[PASS] GZIP header is 100% in sync with DASHBOARD_HTML! ({len(raw_html)} chars -> {len(gz_bytes)} bytes gz)")
        return True
    else:
        if verbose:
            print(f"[FAIL] Content mismatch: decompressed length={len(decompressed)}, source length={len(raw_html)}")
        return False

def update_gz_header(html_text, output_path, verbose=True):
    raw_data, compressed_bytes = compress_html(html_text)
    if verbose:
        print(f"[*] Uncompressed size: {len(raw_data):,} bytes")
        print(f"[*] Compressed GZIP:    {len(compressed_bytes):,} bytes (saved {100.0 - (len(compressed_bytes)*100.0/len(raw_data)):.1f}%)")

    # Round-trip verification
    assert gzip.decompress(compressed_bytes).decode("utf-8") == html_text, "Internal compression verification failed!"

    header_code = generate_header_content(compressed_bytes, len(raw_data))
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    with open(output_path, "w", encoding="utf-8", newline="\n") as f:
        f.write(header_code)

    if verbose:
        print(f"[PASS] Successfully generated: {output_path}")
    return len(raw_data), len(compressed_bytes)

def main():
    parser = argparse.ArgumentParser(description="ESP32 Dashboard HTML GZIP compressor & verifier")
    parser.add_argument("--check", action="store_true", help="Check if existing header is in sync without modifying")
    parser.add_argument("--source", type=str, default=None, help="Source HTML or main.cpp path")
    parser.add_argument("--output", type=str, default=None, help="Output .h path")
    parser.add_argument("--sync-html", action="store_true", help="Sync DASHBOARD_HTML from src/main.cpp to Rice_Dashboard.html")
    parser.add_argument("--from-html", action="store_true", help="Import Rice_Dashboard.html -> src/main.cpp and regenerate GZIP header")
    args = parser.parse_args()

    base_dir, default_main, default_header = get_default_paths()
    source_path = args.source if args.source else default_main
    output_path = args.output if args.output else default_header
    rice_html_path = os.path.join(base_dir, "Rice_Dashboard.html")

    if args.from_html:
        print(f"[*] Importing HTML from {rice_html_path} into {default_main}...")
        raw_html = extract_html_from_file(rice_html_path)
        embed_html_into_main(default_main, raw_html)
        print(f"[PASS] Updated {default_main} with HTML from {rice_html_path}")
        update_gz_header(raw_html, output_path, verbose=True)
        return

    if args.sync_html:
        raw_html = extract_html_from_main(default_main)
        with open(rice_html_path, "w", encoding="utf-8", newline="\n") as f:
            f.write(raw_html)
        print(f"[PASS] Successfully synchronized Rice_Dashboard.html with DASHBOARD_HTML ({len(raw_html)} chars)")
        update_gz_header(raw_html, output_path, verbose=True)
        return

    if args.check:
        is_synced = check_sync(source_path, output_path, verbose=True)
        sys.exit(0 if is_synced else 1)

    print(f"[*] Extracting HTML from: {source_path}")
    if source_path.endswith(".cpp") or source_path.endswith(".h"):
        raw_html = extract_html_from_main(source_path)
    else:
        raw_html = extract_html_from_file(source_path)

    update_gz_header(raw_html, output_path, verbose=True)

if __name__ == "__main__":
    main()
